/**
 * Get a random melody from the database
 */
export function getRandomMelody(): Melody {
  return melodies[Math.floor(Math.random() * melodies.length)];
}

/**
 * Get a melody by ID
 */
export function getMelodyById(id: string): Melody | undefined {
  return melodies.find((m) => m.id === id);
}
